export function getTeamById(id: string): TeamConfig | undefined {
  return TEAMS[id as TeamId];
}

export function getTeamByEmail(email: string): TeamConfig | undefined {
  const normalized = email.trim().toLowerCase();
  return Object.values(TEAMS).find((t) => t.email.toLowerCase() === normalized);
}
